"""Builds a flat, folder-free copy of the app (for uploading with GitHub's file picker).

Output: dist/ with index.html, app.js, app.css, sw.js, manifest.webmanifest and 3 icons.
All ES modules are bundled into app.js (each module keeps its own scope).
Usage:  python3 tools/build_flat.py
"""
import os, re, shutil, json

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DIST = os.path.join(ROOT, 'dist')
ENTRY = 'js/main.js'

IMPORT_RE = re.compile(r"^import\s+(.+?)\s+from\s+'([^']+)';\s*$", re.M)

def resolve(frm, spec):
    return os.path.normpath(os.path.join(os.path.dirname(frm), spec)).replace('\\', '/')

def read(p):
    with open(os.path.join(ROOT, p), encoding='utf-8') as f:
        return f.read()

order, seen, stack = [], set(), set()
def visit(p):
    if p in seen: return
    if p in stack: raise SystemExit('Circular import at ' + p)
    stack.add(p)
    for _, spec in IMPORT_RE.findall(read(p)):
        visit(resolve(p, spec))
    stack.discard(p); seen.add(p); order.append(p)
visit(ENTRY)

def transform(p):
    src = read(p)
    def imp(m):
        what, spec = m.group(1).strip(), resolve(p, m.group(2))
        if what.startswith('* as '):
            return f"const {what[5:].strip()} = __m[{json.dumps(spec)}];"
        names = what.strip('{} ').split(',')
        parts = []
        for n in names:
            n = n.strip()
            if not n: continue
            if ' as ' in n:
                a, b = [x.strip() for x in n.split(' as ')]
                parts.append(f"{a}: {b}")
            else:
                parts.append(n)
        return "const { " + ", ".join(parts) + f" }} = __m[{json.dumps(spec)}];"
    src = IMPORT_RE.sub(imp, src)
    exports = []
    def exp_decl(m):
        exports.append(m.group(3))
        return m.group(1) + m.group(2)
    src = re.sub(r"^(\s*)export\s+((?:async\s+)?function\*?\s+|const\s+|let\s+|class\s+)(\w+)", lambda m: (exports.append(m.group(3)), m.group(1) + m.group(2) + m.group(3))[1], src, flags=re.M)
    def exp_list(m):
        for n in m.group(1).split(','):
            n = n.strip()
            if n: exports.append(n)
        return ''
    src = re.sub(r"^export\s*\{([^}]*)\};?\s*$", exp_list, src, flags=re.M)
    if re.search(r"^\s*(import|export)\s", src, re.M):
        raise SystemExit('Unhandled import/export in ' + p)
    body = "\n".join("  " + l if l else l for l in src.splitlines())
    ret = ", ".join(sorted(set(exports)))
    return f"// ===== {p} =====\n__m[{json.dumps(p)}] = (() => {{\n{body}\n  return {{ {ret} }};\n}})();\n"

bundle = "// Workout Log – bundled build (generated by tools/build_flat.py from the js/ folder).\n'use strict';\nconst __m = {};\n\n" + "\n".join(transform(p) for p in order)

shutil.rmtree(DIST, ignore_errors=True)
os.makedirs(DIST)
with open(os.path.join(DIST, 'app.js'), 'w', encoding='utf-8') as f: f.write(bundle)
shutil.copy(os.path.join(ROOT, 'css/app.css'), os.path.join(DIST, 'app.css'))
for icon in ['icon-192.png', 'icon-512.png', 'apple-touch-icon.png']:
    shutil.copy(os.path.join(ROOT, 'icons', icon), os.path.join(DIST, icon))

html = read('index.html').replace('icons/', '').replace('css/app.css', 'app.css').replace('js/main.js', 'app.js')
open(os.path.join(DIST, 'index.html'), 'w', encoding='utf-8').write(html)
man = read('manifest.webmanifest').replace('icons/', '')
open(os.path.join(DIST, 'manifest.webmanifest'), 'w', encoding='utf-8').write(man)
sw = read('sw.js')
sw = re.sub(r"const FILES = \[.*?\];", """const FILES = [
  './',
  './index.html',
  './app.js',
  './app.css',
  './manifest.webmanifest',
  './icon-192.png',
  './icon-512.png',
  './apple-touch-icon.png',
];""", sw, flags=re.S)
open(os.path.join(DIST, 'sw.js'), 'w', encoding='utf-8').write(sw)
print('Built', len(order), 'modules ->', sorted(os.listdir(DIST)))
